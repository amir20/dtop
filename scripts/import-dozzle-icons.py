#!/usr/bin/env python3
"""Imports Dozzle's app icons as the logos dtop shows next to container names.

Run by hand when Dozzle's icons change; normal builds only embed the output:

    scripts/import-dozzle-icons.py ~/path/to/dozzle

Reads `assets/icons/apps/*.{svg,webp}` and the matching tables in
`assets/utils/appIcons.ts`, then writes:

- `assets/app-logos/<slug>.png`: each icon fitted to a 32x32 transparent square,
  saved losslessly with Pillow's `optimize`
- `src/ui/app_logos_data.rs`: the logo list (sorted, for binary search) and
  Dozzle's matching tables (aliases, distributor namespaces, generic names,
  suffixes), so dtop resolves image names exactly like Dozzle does

Needs `rsvg-convert` (librsvg) on PATH and Pillow with WebP support.
"""

import io
import re
import shutil
import subprocess
import sys
from pathlib import Path

from PIL import Image

SIZE = 32
ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "assets" / "app-logos"
OUT_RS = ROOT / "src" / "ui" / "app_logos_data.rs"


def rasterize(path: Path) -> Image.Image:
    if path.suffix == ".svg":
        png = subprocess.run(
            ["rsvg-convert", "-w", str(SIZE), "-h", str(SIZE), "--keep-aspect-ratio", str(path)],
            check=True,
            capture_output=True,
        ).stdout
        image = Image.open(io.BytesIO(png)).convert("RGBA")
    else:
        image = Image.open(path).convert("RGBA")
    image.thumbnail((SIZE, SIZE), Image.LANCZOS)
    # Center on a square canvas, so every logo scales the same into its cells
    canvas = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    canvas.paste(image, ((SIZE - image.width) // 2, (SIZE - image.height) // 2))
    return canvas


def ts_block(source: str, name: str) -> str:
    match = re.search(rf"const {name}\b[^=]*=\s*(.*?)(?:\]\);|\}};|\);)", source, re.S)
    if not match:
        sys.exit(f"could not find {name} in appIcons.ts")
    return match.group(1)


def string_list(block: str) -> list[str]:
    return sorted(set(re.findall(r'"([^"]+)"', block)))


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    dozzle = Path(sys.argv[1]).expanduser().resolve()
    icons_dir = dozzle / "assets" / "icons" / "apps"
    source = (dozzle / "assets" / "utils" / "appIcons.ts").read_text()

    aliases = dict(
        re.findall(r'^\s*"?([\w.-]+)"?\s*:\s*"([\w.-]+)"', ts_block(source, "ALIASES"), re.M)
    )
    distributors = string_list(ts_block(source, "DISTRIBUTORS"))
    generic = string_list(ts_block(source, "GENERIC"))
    suffix_match = re.search(r"const SUFFIX = /-\(([^)]*)\)\$/", source)
    if not suffix_match:
        sys.exit("could not find SUFFIX in appIcons.ts")
    suffixes = suffix_match.group(1).split("|")

    if OUT_DIR.exists():
        shutil.rmtree(OUT_DIR)
    OUT_DIR.mkdir(parents=True)

    slugs = []
    for path in sorted(icons_dir.iterdir()):
        if path.suffix not in (".svg", ".webp"):
            continue
        rasterize(path).save(OUT_DIR / f"{path.stem}.png", "PNG", optimize=True)
        slugs.append(path.stem)
    slugs.sort()

    # Aliases can only point at logos that exist
    aliases = {k: v for k, v in sorted(aliases.items()) if v in slugs}

    commit = subprocess.run(
        ["git", "-C", str(dozzle), "rev-parse", "--short", "HEAD"],
        capture_output=True,
        text=True,
    ).stdout.strip() or "unknown"

    def rust_strs(items: list[str]) -> str:
        return "".join(f'    "{item}",\n' for item in items)

    lines = [
        f"// @generated by scripts/import-dozzle-icons.py from Dozzle {commit}. Do not edit.",
        "//",
        "// Logos are homarr-labs/dashboard-icons (MIT) as vendored by Dozzle; see",
        "// assets/app-logos/README.md.",
        "",
        "/// Logo slugs and their 32x32 PNGs, sorted by slug",
        "pub(super) static LOGOS: &[(&str, &[u8])] = &[",
        *(
            f'    ("{slug}", include_bytes!("../../assets/app-logos/{slug}.png")),'
            for slug in slugs
        ),
        "];",
        "",
        "/// Image names that don't match their logo's slug, sorted by name",
        "pub(super) static ALIASES: &[(&str, &str)] = &[",
        *(f'    ("{name}", "{slug}"),' for name, slug in aliases.items()),
        "];",
        "",
        "/// Namespaces that repackage other projects' software, sorted",
        f"pub(super) static DISTRIBUTORS: &[&str] = &[\n{rust_strs(distributors)}];",
        "",
        "/// Generic component names that must not match a logo, sorted",
        f"pub(super) static GENERIC: &[&str] = &[\n{rust_strs(generic)}];",
        "",
        "/// Deployment suffixes stripped from an image name (`-alpine`, ...)",
        f"pub(super) static SUFFIXES: &[&str] = &[\n{rust_strs(suffixes)}];",
        "",
    ]
    OUT_RS.write_text("\n".join(lines))

    (OUT_DIR / "README.md").write_text(
        "# App logos\n\n"
        "Generated by `scripts/import-dozzle-icons.py` from Dozzle's app icons "
        f"(Dozzle {commit}); don't edit by hand. Each icon is fitted to 32x32 and saved "
        "as a lossless PNG.\n\n"
        "Most icons come from [homarr-labs/dashboard-icons](https://github.com/homarr-labs/dashboard-icons), "
        "which is MIT licensed. `magpie` comes from "
        "[Magpie's official icon](https://github.com/yetone/magpie), also MIT licensed. "
        "The logos themselves remain the property of their respective projects and are "
        "used here to identify them.\n"
    )

    total = sum(p.stat().st_size for p in OUT_DIR.glob("*.png"))
    print(f"{len(slugs)} logos, {total // 1024} KB, {len(aliases)} aliases")


if __name__ == "__main__":
    main()
